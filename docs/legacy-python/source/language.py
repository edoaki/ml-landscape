"""Language tasks taught through visible inputs, outputs, and local demos."""
from common import *
import language_figures


def body():
    out = sec('tasks', '文章から、何を答えてほしいか',
        p('自然言語処理（natural language processing, NLP）は、人の言葉を計算機で扱う分野です。同じ文章でも、感想を分類する、日時を取り出す、短くまとめる、別の言語へ訳す、というように目的が変われば出力も変わります。まずは身近な案内文で、その違いを見てみましょう。')
        + table(['タスク', '入力 → 出力', '使う場面'], [
            ('文書分類', '文章 → ラベル', '問い合わせを「予約」「変更」「解約」へ振り分ける'),
            ('情報抽出', '文章 → 日時・場所などの項目', '案内文からカレンダーの予定を作る'),
            ('要約', '文章 → 要点を残した短い文章', '会議録から決定事項を読む'),
            ('翻訳', '文章 → 別の言語の文章', '日本語の案内を英語で伝える'),
            ('質問応答', '質問と文脈 → 回答', '受付が何時からかを尋ねる')]))
    out += sec('llm', 'LLM：文章の文脈から、続きを予測する',
        p('LLMは、大量の文章などから言語の予測を学んだモデルです。GPT系の自己回帰モデルは、文脈に続くトークンを一つずつ予測して文章を伸ばします。トークンは文字や単語の一部などの処理単位です。')
        + p('指示や例を入力へ加えることと、追加学習（fine-tuning）でモデルの重みを更新することは別です。計算の仕組みは<a href="transformer.html">Transformer</a>で詳しく扱います。ここからは、外部の資料や画像をどう言語モデルへつなぐかを見ます。'))
    out += sec('rag', 'RAG：質問に近い文書を、ベクトルで探す', language_figures.rag())
    out += sec('vlm', 'VLM：画像の情報と質問を合わせて、文章を作る',
        p('視覚言語モデル（VLM）は画像と言葉を扱うモデルです。まず、画像と質問から文章を生成する型を見ます。同じ猫の写真でも「何色？」「何匹？」で必要な情報が変わります。画像の特徴と質問の両方を使って、回答を作ります。')
        + language_figures.vlm()
        + p('左上の写真は画像エンコーダによって視覚特徴へ変わり、接続部を通って言語モデルへ渡ります。下側の質問もベクトル列へ変わります。言語モデルは両方を文脈として使い、回答を順に生成します。視覚特徴は「猫」「茶色」というラベルをそのまま渡すものではなく、学習された数値の表現です。')
        + p('LLaVAはこの構成の具体例です。初代では画像エンコーダの特徴を線形射影で言語モデルへ接続します。図はこの考え方を簡略化したもので、すべてのVLMが同じ構造ではありません。<a href="vit.html">ViT・VLMの構造</a>も参照してください。')
        + p('写真に写っていない名前などは、画像だけからは分かりません。生成された回答が画像にある事実と対応しているかを確かめる必要があります。'))
    out += sec('matching', 'CLIP：画像と文章を、同じ特徴空間で比べる',
        p('CLIPは画像と言葉の対応を学ぶモデルです。画像エンコーダと文章エンコーダで、それぞれの入力を共通の特徴空間のベクトルへ変えます。「猫の写真」という文と猫の画像のように、対応する組を近い表現にします。')
        + language_figures.clip_space()
        + p('左から来る丸は画像、右から来る四角は文章のベクトルです。色は猫と犬の対応を示しています。元の入力が画素と文字で違っていても、変換後は同じ次元のベクトルとして類似度を計算できます。')
        + sub('学習では、どの画像と文章がペアかを当てる',
            p('画像とその説明文のペアを複数まとめ、画像側と文章側のすべての組み合わせを比べます。正しいペアの類似度が、ほかの組より相対的に高くなるように両方のエンコーダを学習します。これが対照学習（contrastive learning）の考え方です。')
            + language_figures.clip_scores())
        + p('参考：<a href="https://arxiv.org/html/2103.00020v1#S2">CLIP原論文の手法とFigure 1</a>。このページの図は教材独自の模式図です。'))
    out += refs([('LLaVA：公開結果と実装', 'https://llava-vl.github.io/'), ('CLIP：画像と言語の照合', 'https://arxiv.org/abs/2103.00020'), ('RAG：検索と生成の組み合わせ', 'https://arxiv.org/abs/2005.11401')])
    return out
